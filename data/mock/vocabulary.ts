type VocabularySeed = [
  id: string,
  topicId: string,
  hanzi: string,
  pinyin: string,
  vietnamese: string,
  hanViet: string,
  hskLevel: number,
  partOfSpeech: string,
  exampleZh: string,
  examplePinyin: string,
  exampleVn: string,
  measureWord?: string,
  radical?: string,
];

function reviewedLater(seed: VocabularySeed): VocabularyItem {
  const [id, topicId, hanzi, pinyin, vietnamese, hanViet, hskLevel, partOfSpeech, exampleZh, examplePinyin, exampleVn, measureWord, radical] = seed;
  return {
    id,
    topicId,
    hanzi,
    pinyin,
    vietnamese,
    hanViet,
    hskLevel,
    partOfSpeech,
    exampleZh,
    examplePinyin,
    exampleVn: exampleVn.replace(/。$/g, ".").replace(/？$/g, "?"),
    measureWord,
    radical,
    needsReview: true,
  };
}

